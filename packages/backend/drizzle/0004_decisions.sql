CREATE TABLE `decisions` (
	`project_id` text NOT NULL,
	`id` integer NOT NULL,
	`kind` text NOT NULL,
	`decision` text NOT NULL,
	`reason` text NOT NULL,
	`case` text NOT NULL,
	`date` text NOT NULL,
	`status` text NOT NULL,
	`voided_by` integer,
	`void_reason` text,
	`from_submission` integer,
	`from_line` integer,
	`created_at` integer NOT NULL,
	PRIMARY KEY(`project_id`, `id`),
	FOREIGN KEY (`project_id`) REFERENCES `projects`(`id`) ON UPDATE no action ON DELETE no action,
	FOREIGN KEY (`project_id`,`voided_by`) REFERENCES `decisions`(`project_id`,`id`) ON UPDATE no action ON DELETE no action,
	CONSTRAINT "decisions_kind_enum" CHECK("kind" in ('decision', 'later')),
	CONSTRAINT "decisions_status_enum" CHECK("status" in ('active', 'voided')),
	CONSTRAINT "decisions_voided_by" CHECK(("status" = 'voided') = ("voided_by" is not null)),
	CONSTRAINT "decisions_void_reason" CHECK("void_reason" is null or "status" = 'voided'),
	CONSTRAINT "decisions_not_self" CHECK("voided_by" <> "id"),
	CONSTRAINT "decisions_from_line" CHECK(("from_submission" is null) = ("from_line" is null)),
	CONSTRAINT "decisions_date" CHECK("date" glob '[0-9][0-9][0-9][0-9]-[0-9][0-9]-[0-9][0-9]')
);
